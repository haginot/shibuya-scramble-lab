#!/usr/bin/env python3
"""JR v11-en report: writes docs/V11-EN.md and <OUT>/v11-en.md from the data (no hand-kept tables):
the JP → EN string table (tools/v11_strings.mjs), the ghost lines (variants/jr/v11en/ghost.json), the text-fit checks of every
EN frame the recorder rendered (frames.jsonl of the EN CG / HUD / probe renders: CJK, automatic wraps, overflow), the ghost
box checks (protect / core / overlap), and the deliverables (ffprobe duration, size, −14 LUFS / true peak of every file).
usage: python3 tools/v11_report.py
"""
from __future__ import annotations

import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
WORK11 = Path(os.environ.get('WORK11', '/workspace/projects/logs/ssl-claude-halloween/v11-en/render'))
OUT = Path(os.environ.get('OUT', '/workspace/demos/halloween-escape-series/jr-v11-en'))
FIX = OUT/'ja-zone-fix'
PAIRS = ('gate', 'taxi', 'zone', 'alt')
GH = json.loads((ROOT/'web3d/shibuya/series/variants/jr/v11en/ghost.json').read_text(encoding='utf-8'))
EN = json.loads((ROOT/'web3d/shibuya/series/i18n/en.json').read_text(encoding='utf-8'))
FIT_FREE = {'footnote', 'sources', 'simpanel'}


def strings():
    tmp = Path('/tmp/v11-strings.json')
    r = subprocess.run(['node', 'tools/v11_strings.mjs', '--json', str(tmp), '--stride', '3'], cwd=ROOT, capture_output=True, text=True)
    return json.loads(tmp.read_text(encoding='utf-8')), r.stdout.strip(), r.returncode


def fit_stats():
    """every frames.jsonl under $WORK11 (EN CG segments, HUD frames, probes) → counts."""
    st = dict(files=0, frames=0, cjk=0, wraps_hard=0, over=0, wraps_free=0, by_kind={})
    for f in sorted(WORK11.rglob('*.jsonl')):
        kind = 'cg' if '/cg/' in str(f) else 'probe' if '/probe/' in str(f) else 'hud'
        st['files'] += 1; k = st['by_kind'].setdefault(kind, dict(frames=0, issues=0))
        for line in f.open(encoding='utf-8'):
            r = json.loads(line); fit = r.get('fit')
            if fit is None: continue
            st['frames'] += 1; k['frames'] += 1
            hard = [w for w in fit['wraps'] if w['c'] not in FIT_FREE]
            st['cjk'] += bool(fit['cjk']); st['wraps_hard'] += bool(hard); st['over'] += bool(fit['over'])
            st['wraps_free'] += len(fit['wraps'])-len(hard)
            k['issues'] += bool(fit['cjk'] or hard or fit['over'])
    return st


def probe(path):
    q = lambda *a: subprocess.run(['ffprobe', '-v', 'error', *a, str(path)], capture_output=True, text=True).stdout.strip()
    d = float(q('-show_entries', 'format=duration', '-of', 'csv=p=0') or 0)
    r = subprocess.run(['ffmpeg', '-nostats', '-i', str(path), '-filter_complex', 'ebur128=peak=true', '-f', 'null', '-'], capture_output=True, text=True).stderr
    tail = r[r.rfind('Summary:'):]
    m1, m2 = re.search(r'I:\s+(-?[\d.]+) LUFS', tail), re.search(r'Peak:\s+(-?[\d.]+) dBFS', tail)
    return dict(duration=round(d, 2), mb=round(path.stat().st_size/2**20, 1), lufs=float(m1.group(1)) if m1 else None, tp=float(m2.group(1)) if m2 else None)


def md_cell(s): return s.replace('|', '\\|').replace('\n', ' / ')


def build():
    S, sline, rc = strings()
    fs = fit_stats()
    L = []
    w = L.append
    w('# JR編 v11-en: the English edition of the four v10.2 videos (2026-10-29)\n')
    w('Owner request (HAGINO): 「英語版も作成だ！世界で流行らせよう」. Brief: `logs/ssl-claude-halloween/v11-en/brief.md`.\n')
    w(f'Deliverables: `{OUT}/` (`gate|taxi|zone|alt.mp4`, `<pair>-share.mp4` (x264 crf 23, < 200 MB), `<pair>-contact.jpg`,')
    w('`proof/` stills of every text-heavy EN scene, `licenses.md`), and the JP zone wrap fix in `ja-zone-fix/`.')
    w('The Japanese videos in `jr-v10.2/` are untouched.\n')
    w('## How the EN build works (one code path, a language switch)')
    w('- **Text**: the JP configs and components stay the source of truth. With `lang=en` (page URL; `tools/record_variant.py --lang en`)')
    w('  every displayed string is looked up in `web3d/shibuya/series/i18n/en.json` (generated by `tools/v11_en_dict.py`: one JP → EN')
    w('  table, exact strings + 4 number patterns). `GameHUD.frame` translates the frame state (`trDeep`) and the text between tags of')
    w('  the rendered HTML (`trHtml`, for the words hard-coded in `ui/components.mjs`). With `lang=ja` both are the identity:')
    w('  the JP HUD HTML of 976 sampled states is byte-identical to v10.2 (7ec8667), the only diff being the zone wrap fix (test).')
    w('- **Layout in EN**: the display-font fit (`fitFs`, end card, gag) measures Latin widths (Dela Gothic One metrics); the goodbye')
    w('  card shows the EN text once (no JP/EN double lines); tab sub-labels that only repeat the tab word are dropped ("SIM" +')
    w('  「シミュレーション」 → "SIMULATION").')
    w('- **3D logo**: `tools/build_logo_glyphs.py --lang en` → `web3d/data/logo_glyphs_en.json` / `logo_sdf_en.png` / `logo_halo_en.png`')
    w('  ("ESCAPE FROM / HALLOWEEN / SHIBUYA!" + "JR" ticket + "10/31 HOW DO YOU GET HOME?"; same OFL fonts, which have full')
    w('  Latin coverage). The JP logo files rebuild byte-identically.')
    w('- **Pictures**: every non-photo beat is re-rendered in 3D with the EN HUD (`tools/v11_render.py cg`). v10 reused older')
    w('  v6 / v7 / v8 CG frames for some beats, but their HUD is burnt in Japanese. The photo beats get an EN HUD layer')
    w('  (`tools/v11_render.py hud`), composited by `tools/v11_composite.py` (= `tools/v10_composite.py` on the EN layers, plus')
    w('  the EN AI-image tag on the crush POV). Same timeline (121.7 s, 3651 frames), configs, sim, plates, cuts and audio cues.')
    w('- **Ghost**: `tools/v11_ghost.py` (EN lines, boxes re-checked against the EN HUD), drawn by the same `tools/v9_ghost.py`.')
    w('- **Audio**: the JP build has no TTS or voice narration (captions + procedural SFX / music; the ghost\'s "voice" is')
    w('  synthesized blips). So the EN build is **captions-only** too: the same cue sheet and mix chain (`tools/v11_finish.py` =')
    w('  `tools/v10_finish.py`), −14 LUFS integrated, −2 dBTP master ceiling.\n')
    w('## Checks')
    w(f'- **Every string translated** (`node tools/v11_strings.mjs`, the page\'s per-frame HUD state in node, every 3rd frame of all')
    w(f'  4 videos): `{sline}`. The fiction word appears on the cold open\'s mission card only (the FICTION tag).')
    w(f'- **Rendered text fit** (browser, `ui/components.mjs measureFit`, every EN frame the recorder rendered: CG segments, HUD')
    w(f'  frames, layout probes; the recorder stops on any hard issue): {fs["frames"]} frames in {fs["files"]} logs '
      f'({", ".join(f"{k} {v["frames"]}" for k, v in fs["by_kind"].items())}). CJK on screen **{fs["cjk"]}**,')
    w(f'  automatic line wrap outside paragraph boxes **{fs["wraps_hard"]}**, text overflowing its box / the frame **{fs["over"]}**.')
    w(f'  Paragraph boxes that may wrap on their own (footnote, sources card, sim panel notes): {fs["wraps_free"]} wrapped lines, none overflowing.')
    w('  English is longer than Japanese: lines were shortened, never set below the JP font sizes.')
    gl = [l for p in PAIRS for l in GH['pairs'][p]['lines']]
    mx = max(len(r) for l in gl for r in l['text'].split('\n'))
    bad = [(p, l['beat'], l['protect'], l['core'], l['overlap']) for p in PAIRS for l in GH['pairs'][p]['lines'] if l['protect'] or l['core'] or l['overlap']]
    w(f'- **Ghost bubbles** ({len(gl)} lines): ≤ 2 lines, longest line {mx} chars (rule ≤ 24), every bubble ≤ the widest JP bubble')
    w(f'  ({GH["rules"]["jpMaxWidth"]} px); reading time 1.0 s + 0.05 s/char inside the window; boxes vs the EN HUD probes and the photo')
    w('  faces / sign panel: **protect 0 on every line**; HUD core 0 and overlap 0 on every line except these, which are the')
    w('  same beats JP v10.2 accepts (`v9_ghost.ALLOW_OVERLAP`: the full sim map of SIM PICK / gut pick, where the ghost grazes a')
    w('  route pin and covers no text; clear-cheat: the 12 px margin around the cheat sheet only, core 0). Format: pair beat (core px / overlap px):')
    w('  ' + ', '.join(f'{p} {b} ({c} / {o})' for p, b, _, c, o in bad) + '. JP v10.2 for comparison: gate sim-pick (2921 / 7333),')
    w('  taxi over-choice (512 / 6533), zone clear-cheat (0 / 384), alt over-choice (871 / 3349), alt clear-cheat (0 / 1235).')
    moved = sorted({(p, l['beat']) for p in PAIRS for l in GH['pairs'][p]['lines'] if l.get('moved')})
    w(f'  Boxes moved from the v10.2 place (EN HUD / bubble size): {", ".join(f"{p} {b}" for p, b in moved) or "none"}.\n')
    w('## Deliverables')
    w('| file | duration (s) | size (MB) | integrated (LUFS) | true peak (dBTP) |')
    w('|---|---|---|---|---|')
    for p in PAIRS:
        for f in (OUT/f'{p}.mp4', OUT/f'{p}-share.mp4'):
            if f.exists(): r = probe(f); w(f'| `{f.name}` | {r["duration"]} | {r["mb"]} | {r["lufs"]} | {r["tp"]} |')
    for f in (FIX/'zone.mp4', FIX/'zone-share.mp4'):
        if f.exists(): r = probe(f); w(f'| `ja-zone-fix/{f.name}` | {r["duration"]} | {r["mb"]} | {r["lufs"]} | {r["tp"]} |')
    w('The mix is limited at −2 dBTP on the master WAV, as in JP. The AAC files measure −1.6 to −1.8 dBTP, the same as JP v10.2')
    w('(`verify` limit −1.0 dBTP). Every share file is under 200 MB.\n')
    w('## JP zone wrap fix')
    w('「スクランブル交差点：一歩も前に進めない」 (zone crush-pov caption) wrapped its last character onto a second line (since v10.1).')
    w('It is now 「スクランブル交差点：一歩も進めない」 (`tools/v10_configs.mjs` FIXES; same meaning). Only that beat\'s JP HUD frames')
    w('were re-rendered (`tools/v10_hud.py`), and the zone ghost box was re-checked. The JP zone video is in `ja-zone-fix/zone.mp4` + `zone-share.mp4`;')
    w('`jr-v10.2/` is untouched. EN: "Scramble Crossing: can\'t move an inch".\n')
    w('## Not changed')
    w('- Story, structure (TRUE END for not going; "Don\'t go to Shibuya Halloween"), beats, timing, sim runs and numbers, plates,')
    w('  costumes, crush POV, kaiju, cuts, SFX / music, the ghost\'s design and line starts.')
    w('- In-world 3D signage stays as on site. The station name boards are bilingual JP / EN like the real ones, and the taxi-stand /')
    w('  closure boards are Japanese props whose meaning is in the EN captions. Photo-plate signage was already blurred.')
    w('- The facts: every number, date and time is the JP text\'s, with the same source ids (JR-GATE-xx, …). Source names are the')
    w('  EN names of `sources-series.mjs`. Japan-specific places get one short gloss where first on screen: Hachiko ("the dog')
    w('  statue meetup spot"), the Scramble Crossing ("the famous all-way crossing"), "Shibuya-kei = 90s cool" (ghost). Last')
    w('  trains, Miyamasuzaka, Sakuragaokacho and the Yamanote loops are explained by their captions.\n')
    w('## Open items')
    w('- **Before posting on 10/31**, re-check JR East\'s 2026 Halloween measures (gate limits, "not announced as of Oct 25"), the')
    w('  last trains (normal weekend timetable, checked 10/25; any 2026 special timetable), the taxi stands (West Exit stand')
    w('  paused since 2025-03-30, no reopening announced as of 10/25), and the police closure notice. These apply to the EN and')
    w('  JP videos alike.')
    w('- The EN copy is written for a global audience (arcade tone, not literal). A native-speaker read-through before posting is welcome.\n')
    w('## Ghost lines (EN)')
    w('| pair | beat | start–end (s) (JP end) | JP | EN |')
    w('|---|---|---|---|---|')
    for p in PAIRS:
        for l in GH['pairs'][p]['lines']:
            w(f'| {p} | {l["beat"]} | {l["t0"]:.2f}–{l["t1"]:.2f} ({l["jp_t1"]:.2f}) | {md_cell(l["ja"])} | {md_cell(l["text"])} |')
    w('')
    w('## String table (JP → EN, every on-screen string per video / beat)')
    w('Generated from the page\'s HUD states (`tools/v11_strings.mjs`). Footnotes are built in EN from the source table (not translated');
    w('strings). Words hard-coded in the components (tabs, panel headers) are listed after it.\n')
    w('| where | JP | EN |')
    w('|---|---|---|')
    seen = set()
    for r in S['table']:
        if r['ja'].startswith('出典：') or r['ja'].startswith('Sources'): continue
        k = (r['where'], r['ja'])
        if k in seen: continue
        seen.add(k); w(f'| {r["where"]} | {md_cell(r["ja"])} | {md_cell(r["en"])} |')
    w('\n### Component words, cheat sheets, lessons, choices (exact entries of `i18n/en.json` not listed above)')
    w('| JP | EN |')
